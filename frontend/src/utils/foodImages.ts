// Default fallback photo: authentic warm Indian vegetarian thali / dal bowl
export const DEFAULT_FOOD_PHOTO = 'https://commons.wikimedia.org/wiki/Special:FilePath/Sambar.JPG?width=800'

export function getFoodPhoto(name?: string, category?: string): string {
  if (!name) {
    if (category && CATEGORY_PHOTOS[category.toUpperCase()]) {
      return CATEGORY_PHOTOS[category.toUpperCase()]
    }
    return DEFAULT_FOOD_PHOTO
  }

  const clean = name.toLowerCase().trim()

  // 1. Direct exact key match
  if (FOOD_PHOTOS[clean]) {
    return FOOD_PHOTOS[clean]
  }

  // 2. Remove parenthetical state/prep suffix like " (tn)", " (ka)", " (up)", " (wb)", " (mh)", " (cooked)", " (steamed)"
  const normalized = clean.replace(/\s*\([a-z0-9\s,\/]+\)/gi, '').trim()
  if (FOOD_PHOTOS[normalized]) {
    return FOOD_PHOTOS[normalized]
  }

  // 3. Ranked key match: sort dictionary keys by length in descending order
  // This guarantees specific multi-word dishes (e.g., "bisi bele bath", "ragi mudde", "puliyodarai", "lemon rice", "curd rice", "pongal")
  // match before short generic fallback words like "rice" or "roti"
  const sortedKeys = Object.keys(FOOD_PHOTOS).sort((a, b) => b.length - a.length)

  for (const key of sortedKeys) {
    if (clean.includes(key) || normalized.includes(key)) {
      return FOOD_PHOTOS[key]
    }
  }

  // 4. Reverse containment check
  for (const key of sortedKeys) {
    if (key.includes(normalized) || key.includes(clean)) {
      return FOOD_PHOTOS[key]
    }
  }

  // 5. Category match fallback
  if (category && CATEGORY_PHOTOS[category.toUpperCase()]) {
    return CATEGORY_PHOTOS[category.toUpperCase()]
  }

  return DEFAULT_FOOD_PHOTO
}
